#!/usr/bin/env node
/**
 * engram-mcp — the npx entrypoint for Engram's stdio bridge.
 *
 * Two-component setup (see README): the server runs via docker compose;
 * every MCP client spawns THIS command as its stdio server. Modes:
 *
 *   engram-mcp             run the stdio↔HTTP bridge (default; what MCP
 *                          clients invoke — reads API_KEY/MCP_HOST/MCP_PORT)
 *   engram-mcp init        first-run wizard: print secret-free config for
 *                          Claude Code, Codex, Cursor and Claude Desktop.
 *                          --write-env generates an API key and writes ./.env
 *                          (never overwrites an existing one).
 *   engram-mcp --help      this text
 *
 * The wizard never prints credential bytes, contacts a server, or overwrites
 * existing files — closed-safe by default.
 */

const crypto = require('crypto');
const fs = require('fs');
const path = require('path');

const PKG = require(path.join(__dirname, '..', 'package.json'));
const PKG_NAME = PKG.name;
// P1 compatibility seam: the legacy package keeps every existing string and
// config key, while the private HYTHE overlay opts into the new public-facing
// identity. Runtime/database names remain compatibility-pinned until P4.
const HYTHE_DISTRIBUTION = PKG.hytheDistribution === true;
const PRODUCT_NAME = HYTHE_DISTRIBUTION ? 'HYTHE' : 'Engram';
const CLI_NAME = HYTHE_DISTRIBUTION ? 'hythe-mcp' : 'engram-mcp';
const SERVER_KEY = HYTHE_DISTRIBUTION ? 'hythe' : 'engram';
const KEY_FILE_ENV = HYTHE_DISTRIBUTION ? 'HYTHE_API_KEY_FILE' : 'ENGRAM_API_KEY_FILE';
const AGENT_ID_ENV = HYTHE_DISTRIBUTION ? 'HYTHE_AGENT_ID' : 'ENGRAM_AGENT_ID';
const DEFAULT_HOST = '127.0.0.1';
const DEFAULT_PORT = '6174';

function helpText() {
  return [
    `${PKG_NAME} — ${PRODUCT_NAME} stdio bridge + first-run wizard`,
    '',
    'Usage:',
    `  ${CLI_NAME}             run the stdio bridge (env: ${AGENT_ID_ENV} + API_KEY or ${KEY_FILE_ENV})`,
    `  ${CLI_NAME} init        print secret-free MCP client config blocks`,
    `    --agent-id <agent-id> stable client-lane identity (${HYTHE_DISTRIBUTION ? 'required' : 'recommended'})`,
    '    --write-env          generate an API key + write ./.env (mode 600; write-once)',
    '    --host <host>        bridge target host in printed configs (default 127.0.0.1)',
    '    --port <port>        bridge target port in printed configs (default 6174)',
    `  ${CLI_NAME} demo        seed a small two-agent coordination demo (demo-*`,
    '                         namespaced; env: API_KEY, MCP_HOST, MCP_PORT)',
    `  ${CLI_NAME} --help      show this help`,
    '',
    'Typical first run:',
    `  1. npx -y ${PKG_NAME} init --write-env --agent-id my-agent`,
    '  2. docker compose -f docker/docker-compose.yml up -d',
    '  3. paste the printed block into your MCP client config',
  ].join('\n');
}

function generateApiKey() {
  return crypto.randomBytes(32).toString('base64');
}

function envFileContent(key) {
  return [
    `# ${PRODUCT_NAME} configuration — generated by \`${CLI_NAME} init\`.`,
    '# The same API_KEY authenticates the server middleware AND the stdio bridge.',
    `API_KEY=${key}`,
    '',
    '# --- Server ---',
    `NEURAL_MCP_PORT=${DEFAULT_PORT}`,
    'NEURAL_DB_PATH=./data/engram.db',
    '',
    '# --- Stdio bridge (per MCP client) ---',
    `MCP_HOST=${DEFAULT_HOST}`,
    `MCP_PORT=${DEFAULT_PORT}`,
    '',
    '# --- Optional hardening ---',
    '# Comma-separated browser origins allowed by CORS. Unset = no cross-origin',
    '# browser access (closed-safe default). Same-origin and non-browser',
    '# clients (the bridge, curl) are unaffected.',
    '# CORS_ORIGINS=',
    '',
  ].join('\n');
}

function shellQuote(value) {
  return `'${String(value).replace(/'/g, `'\\''`)}'`;
}

function configBlocks(keyFilePath, host, port, agentId) {
  const env = {
    [KEY_FILE_ENV]: keyFilePath,
    ...(agentId ? { [AGENT_ID_ENV]: agentId } : {}),
    MCP_HOST: host,
    MCP_PORT: String(port),
  };
  const clientJson = JSON.stringify(
    { mcpServers: { [SERVER_KEY]: { command: 'npx', args: ['-y', PKG_NAME], env } } },
    null,
    2
  );

  return [
    '─── Claude Code ─────────────────────────────────────────────────────',
    'Run:',
    `  claude mcp add ${SERVER_KEY} --env ${KEY_FILE_ENV}=${shellQuote(keyFilePath)}`
      + (agentId ? ` --env ${AGENT_ID_ENV}=${shellQuote(agentId)}` : '')
      + ` --env MCP_HOST=${shellQuote(host)} --env MCP_PORT=${shellQuote(port)} -- npx -y ${PKG_NAME}`,
    ...(agentId ? [
      '',
      'Claude plugin hooks are separate child processes; bind the same identity when launching this lane:',
      `  ${AGENT_ID_ENV}=${shellQuote(agentId)} claude`,
    ] : []),
    '',
    'Or add to .mcp.json / ~/.claude.json:',
    clientJson,
    '',
    '─── Codex (~/.codex/config.toml) ────────────────────────────────────',
    `[mcp_servers.${SERVER_KEY}]`,
    'command = "npx"',
    `args = ["-y", "${PKG_NAME}"]`,
    `env = { ${KEY_FILE_ENV} = ${JSON.stringify(keyFilePath)}, `
      + (agentId ? `${AGENT_ID_ENV} = ${JSON.stringify(agentId)}, ` : '')
      + `MCP_HOST = ${JSON.stringify(host)}, MCP_PORT = ${JSON.stringify(String(port))} }`,
    '',
    '─── Cursor (.cursor/mcp.json) ───────────────────────────────────────',
    clientJson,
    '',
    '─── Claude Desktop (claude_desktop_config.json) ─────────────────────',
    clientJson,
  ].join('\n');
}

function normalizeAgentId(value) {
  const normalized = typeof value === 'string' ? value : '';
  if (
    normalized.length < 1
    || normalized.length > 100
    || !/^[A-Za-z0-9_.:-]+$/.test(normalized)
  ) {
    throw new Error('--agent-id must be 1-100 characters from A-Z, a-z, 0-9, _, ., :, or -');
  }
  return normalized;
}

function parseInitAgentId(argv) {
  const positions = argv
    .map((value, index) => value === '--agent-id' ? index : -1)
    .filter((index) => index !== -1);
  if (positions.length > 1) {
    throw new Error('--agent-id may be specified only once');
  }
  if (positions.length === 0) {
    if (HYTHE_DISTRIBUTION) throw new Error('--agent-id is required');
    return null;
  }
  const value = argv[positions[0] + 1];
  if (value == null || value.startsWith('--')) {
    throw new Error('--agent-id needs a value');
  }
  return normalizeAgentId(value);
}

function runInit(argv) {
  const writeEnv = argv.includes('--write-env');
  const hostIdx = argv.indexOf('--host');
  const portIdx = argv.indexOf('--port');
  const host = hostIdx !== -1 ? argv[hostIdx + 1] : DEFAULT_HOST;
  const port = portIdx !== -1 ? argv[portIdx + 1] : DEFAULT_PORT;
  if (!host || !port) {
    process.stderr.write(`${CLI_NAME} init: --host/--port need a value\n`);
    process.exit(2);
  }

  let agentId;
  try {
    agentId = parseInitAgentId(argv);
  } catch (error) {
    process.stderr.write(`${CLI_NAME} init: ${error.message}\n`);
    process.exit(2);
  }

  const envPath = path.resolve(process.cwd(), '.env');
  const lines = [];
  lines.push(`${PRODUCT_NAME} first-run wizard`);
  lines.push('');

  if (writeEnv) {
    try {
      const key = generateApiKey();
      fs.writeFileSync(envPath, envFileContent(key), { mode: 0o600, flag: 'wx' });
      lines.push(`Generated an API key and wrote ${envPath} (mode 600).`);
      lines.push('The credential was not printed; the client blocks reference that file.');
      lines.push('');
    } catch (error) {
      if (error && error.code !== 'EEXIST') throw error;
      process.stderr.write(
        `${CLI_NAME} init: ./.env already exists — refusing to overwrite. ` +
          `Rerun without --write-env to print config that references ${envPath}.\n`
      );
      process.exitCode = 1;
      return;
    }
  } else {
    lines.push('No credential file was written and no API key was generated.');
    lines.push(`The client blocks reference ${envPath}.`);
    lines.push(`Create that file with mode 600 and an API_KEY entry, or rerun ${CLI_NAME} init --write-env.`);
    lines.push('');
  }

  lines.push('Start the server:  docker compose -f docker/docker-compose.yml up -d');
  lines.push('Then paste the block for your client:');
  lines.push('');
  lines.push(configBlocks(envPath, host, port, agentId));
  lines.push('');
  process.stdout.write(lines.join('\n') + '\n');
}

function parseApiKeyFile(contents) {
  const envMatch = contents.match(/^(?:export\s+)?API_KEY\s*=\s*(.*)$/m);
  let key = envMatch ? envMatch[1].trim() : contents.trim();
  if ((key.startsWith('"') && key.endsWith('"')) || (key.startsWith("'") && key.endsWith("'"))) {
    key = key.slice(1, -1);
  }
  if (!key || key.includes('\n') || key.includes('\r') || key === 'CHANGE_ME') {
    throw new Error('credential file does not contain a usable API_KEY');
  }
  return key;
}

function loadApiKeyFromFile() {
  if (process.env.API_KEY) return;
  const keyFileVariable = [KEY_FILE_ENV, 'HYTHE_API_KEY_FILE', 'ENGRAM_API_KEY_FILE']
    .find((name, index, names) => names.indexOf(name) === index && process.env[name]);
  if (!keyFileVariable) return;

  const keyFilePath = path.resolve(process.env[keyFileVariable]);
  const stat = fs.statSync(keyFilePath);
  if (!stat.isFile()) throw new Error(`${keyFileVariable} must point to a regular file`);
  const permissions = stat.mode & 0o777;
  if (process.platform !== 'win32' && permissions !== 0o400 && permissions !== 0o600) {
    throw new Error(`${keyFileVariable} must point to a mode-400 or mode-600 file`);
  }
  process.env.API_KEY = parseApiKeyFile(fs.readFileSync(keyFilePath, 'utf8'));
}

function prepareCredential(mode) {
  try {
    loadApiKeyFromFile();
    return true;
  } catch (error) {
    process.stderr.write(`${CLI_NAME} ${mode}: ${error.message}\n`);
    process.exitCode = 2;
    return false;
  }
}

// --- demo seed -------------------------------------------------------------
// Optional, additive, and prefix-namespaced (demo-*): seeds a minimal
// two-agent coordination story over the live HTTP contract so an outsider
// sees supersession + resume/checkpoint + messaging working within minutes.
// The DB ships empty; removing the demo = `docker compose down -v` (docs).

function jsonrpcCall(host, port, apiKey, name, args) {
  const http = require('http');
  const body = JSON.stringify({
    jsonrpc: '2.0',
    id: 1,
    method: 'tools/call',
    params: { name, arguments: args },
  });
  return new Promise((resolveCall, rejectCall) => {
    const req = http.request(
      {
        hostname: host,
        port,
        path: '/mcp',
        method: 'POST',
        headers: {
          'Content-Type': 'application/json',
          'Content-Length': Buffer.byteLength(body),
          'x-api-key': apiKey,
        },
      },
      (res) => {
        let data = '';
        res.on('data', (d) => (data += d));
        res.on('end', () => {
          try {
            const json = JSON.parse(data);
            if (json.error) return rejectCall(new Error(`${name}: ${JSON.stringify(json.error)}`));
            if (json.result && json.result.isError) {
              return rejectCall(new Error(`${name}: ${json.result.content?.[0]?.text || 'tool error'}`));
            }
            resolveCall(json.result);
          } catch (e) {
            rejectCall(new Error(`${name}: bad response (${String(e)}) — ${data.slice(0, 200)}`));
          }
        });
      }
    );
    req.on('error', (e) => rejectCall(new Error(`${name}: ${e.message}`)));
    req.end(body);
  });
}

async function runDemo() {
  const host = process.env.MCP_HOST || DEFAULT_HOST;
  const port = parseInt(process.env.MCP_PORT || DEFAULT_PORT, 10);
  const apiKey = process.env.API_KEY;
  if (!apiKey) {
    process.stderr.write(`${CLI_NAME} demo: API_KEY env var is required (same key as the server)\n`);
    process.exit(2);
  }
  const call = (name, args) => jsonrpcCall(host, port, apiKey, name, args);

  process.stdout.write(`Seeding the two-agent demo against http://${host}:${port} …\n`);
  await call('register_agent', { agentId: 'demo-alice', name: 'Demo Alice', capabilities: ['builder'] });
  await call('register_agent', { agentId: 'demo-bob', name: 'Demo Bob', capabilities: ['reviewer'] });
  await call('create_entities', {
    entities: [{
      name: 'demo-fleet-project',
      entityType: 'project',
      observations: [`Demo project: two agents coordinating through ${PRODUCT_NAME}. Safe to delete.`],
    }],
  });
  await call('checkpoint', {
    agentId: 'demo-alice',
    scope: { project: 'demo-fleet-project' },
    expectedRevision: null,
    idempotencyKey: 'demo-seed-alice-1',
    state: {
      objective: 'Show a second agent resuming shared state',
      status: 'green',
      owner: 'demo-alice',
      nextActions: ['demo-bob resumes this scope and reads this state'],
      blockers: [],
      guardrails: ['demo data only — wipe with docker compose down -v'],
    },
  });
  await call('send_ai_message', {
    from: 'demo-alice',
    to: 'demo-bob',
    content: 'Checkpoint written for demo-fleet-project — resume the scope and take over.',
    messageType: 'info',
  });
  const resumed = await call('resume', {
    agentId: 'demo-bob',
    scope: { project: 'demo-fleet-project' },
    budget: 4000,
  });
  const bundle = JSON.parse(resumed.content[0].text);

  process.stdout.write(
    [
      '',
      'Demo seeded. What just happened:',
      '  1. demo-alice wrote a checkpoint (structured state, CAS revision 1)',
      '  2. demo-alice messaged demo-bob on the bus',
      `  3. demo-bob resumed the scope and read alice's state: "${bundle.working.objective}" [${bundle.working.status}]`,
      '',
      'Explore from your MCP client:',
      "  resume({agentId: 'demo-bob', scope: {project: 'demo-fleet-project'}, budget: 4000})",
      "  get_ai_messages({agentId: 'demo-bob'})",
      '',
      'Everything is prefixed demo- and the DB shipped empty:',
      '  wipe it all with `docker compose -f docker/docker-compose.yml down -v`.',
      '',
    ].join('\n')
  );
}

const argv = process.argv.slice(2);
if (argv.includes('--help') || argv.includes('-h') || argv[0] === 'help') {
  process.stdout.write(helpText() + '\n');
} else if (argv[0] === 'init') {
  runInit(argv.slice(1));
} else if (argv[0] === 'demo') {
  if (prepareCredential('demo')) runDemo().catch((e) => {
    process.stderr.write(`${CLI_NAME} demo: ${e.message}\n`);
    process.exit(1);
  });
} else if (argv.length === 0 || argv[0] === 'bridge') {
  // Default mode: hand the process over to the stdio bridge.
  if (prepareCredential('bridge')) {
    require(path.join(__dirname, '..', 'mcp-stdio-http-bridge.cjs'));
  }
} else {
  process.stderr.write(`${CLI_NAME}: unknown command '${argv[0]}'\n\n` + helpText() + '\n');
  process.exit(2);
}
